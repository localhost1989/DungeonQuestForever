-- Builds the table of what the bosses of the runs drop, from the installed QuestieDB.
-- Run from this folder: /private/tmp/dprep-lua54/lua make-loot.lua > loot-table.txt
-- Weapons and armour only; a thing a crowd of creatures drops is not a boss's own.
GetLocale = function() return "ruRU" end
local here = arg[0]:match("^(.*[/])") or "./"
dofile(here .. "questie-offline.lua")
local source = io.open(here .. "../ForeverDungeonPrep/Ways.lua"):read("a")
local bosses = {}
for id in source:gmatch("npc=(%d+)") do bosses[tonumber(id)] = true end
for list in source:gmatch("also=(%b{})") do
    for id in list:gmatch("%d+") do bosses[tonumber(id)] = true end
end
local loot = {}
for _, id in ipairs(ItemDB.GetAllIds()) do
    local ok, drops = pcall(ItemDB.Get, id, "npcDrops")
    if ok and type(drops) == "table" and #drops > 0 and #drops <= 8 then
        local class, sub = ItemDB.Get(id, "class"), ItemDB.Get(id, "subClass")
        if class == 2 or class == 4 then
            for _, npc in ipairs(drops) do
                if bosses[npc] then
                    loot[npc] = loot[npc] or {}
                    table.insert(loot[npc], {id=id, class=class, sub=sub or 0, level=ItemDB.Get(id, "itemLevel") or 0})
                end
            end
        end
    end
end
local ids = {}
for npc in pairs(loot) do ids[#ids+1] = npc end
table.sort(ids)
print("-- BEGIN LOOT: generated by dungeon-quest-handoff/make-loot.lua from QuestieDB; do not edit by hand")
print("-- [boss] = {item, class (2 weapon, 4 armour), subclass, ...}")
print("P.Loot = {")
local total = 0
for _, npc in ipairs(ids) do
    table.sort(loot[npc], function(a, b) if a.level ~= b.level then return a.level > b.level end return a.id < b.id end)
    local parts = {}
    for _, item in ipairs(loot[npc]) do parts[#parts+1] = item.id .. "," .. item.class .. "," .. item.sub; total = total + 1 end
    print(("    [%d]={%s},"):format(npc, table.concat(parts, ", ")))
end
print("}")
print("-- END LOOT")
io.stderr:write(#ids .. " bosses, " .. total .. " things\n")
