# Лучшие вещи для окна «Лучшие вещи»: списки timesaver.gg (по весам характеристик каждой ветки,
# для каждого уровня через 5 и для каждой стороны), сохранённые в gear-source/*.json.
# Обновить списки: скачать заново страницы https://timesaver.gg/tools/wow-forever/leveling-gear/<класс>/<ветка>,
# вынуть из них объект {"picks":...,"items":...} в gear-source/<класс>-<ветка>.json, затем
#   python3 make-gear.py   — пишет ../ForeverDungeonPrep/GearData.lua
import glob, io, json, os, subprocess

STAMP = "13.11.2026"
SLOTS = 17

def lua(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

classes, items = {}, {}
for path in sorted(glob.glob("gear-source/*.json")):
    o = json.load(io.open(path, encoding="utf-8"))
    cls = o["className"].upper()
    spec = os.path.basename(path)[:-5].split("-", 1)[1]
    picks = {}
    for key, row in o["picks"].items():
        assert len(row) == SLOTS, (path, key)
        picks[key] = ",".join(str(i or 0) for i in row)
        for i in row:
            if i: items[i] = o["items"][str(i)]
    classes.setdefault(cls, []).append((spec, picks))

# The Russian names and the zones, from QuestieDB (the newest one, with the dungeons of Forever).
ask = []
for i in sorted(items):
    ask.append("item %d" % i)
    for s in items[i][5]:
        if s[0] in "dnv" and s[4]: ask.append("npc %d" % s[4])
        if s[0] == "q" and s[4]: ask.append("quest %d" % s[4])
env = dict(os.environ)
env.setdefault("QDB_ROOT", "/private/tmp/claude-501/-Users-aleksey-Documents/ca2fbd79-cd6b-413f-b39c-cf98ef669709/scratchpad/qdb111/unz/QuestieDB/")
said = subprocess.run(["/private/tmp/dprep-lua54/lua", "make-gear-names.lua"], input="\n".join(sorted(set(ask))) + "\n",
    capture_output=True, text=True, env=env, check=True).stdout
ru, area = {}, {}
for line in said.splitlines():
    key, name, zone = line.split("\t")
    ru[key], area[key] = name, int(zone)

out = io.StringIO()
w = out.write
w("local _, P = ...\n")
w("-- Generated by dungeon-quest-handoff/make-gear.py from the gear lists of timesaver.gg (%s); do not edit by hand.\n" % STAMP)
w("-- [item] = {quality, required level, icon, English name, Russian name, sources...}; a source is\n")
w("-- \"kind|side|id|area|who|who in Russian|where\": kind d boss of a dungeon, q quest, n named creature, v vendor,\n")
w("-- c crafted (who is the craft); side a, h or b (both); area the zone of the game, 0 when not known.\n")
w("P.GearStamp = %s\n" % lua(STAMP))
w("P.GearItems = {\n")
for i in sorted(items):
    it = items[i]
    name, quality, icon, need, _, sources = it
    parts = [str(quality), str(need or 0), lua(icon or ""), lua(name), lua(ru.get("item %d" % i, ""))]
    for s in sources:
        kind, who, where, side, ref = s
        key = ("quest %d" if kind == "q" else "npc %d") % (ref or 0)
        whoRu = ru.get(key, "") if kind != "c" else ""
        zone = area.get(key, 0) if kind != "c" else 0
        parts.append(lua("%s|%s|%s|%d|%s|%s|%s" % (kind, side, ref or 0, zone, who or "", whoRu, where or "")))
    w("[%d]={%s},\n" % (i, ",".join(parts)))
w("}\n")
w("-- [class] = the specs in the order of the talent tabs; each: [level .. side] = the item of the 17 places\n")
w("-- (head, neck, shoulder, back, chest, wrist, hands, waist, legs, feet, finger, finger, trinket, trinket,\n")
w("-- main hand, off hand, ranged), 0 where nothing is clearly better.\n")
w("P.GearPicks = {\n")
for cls in sorted(classes):
    w("%s={\n" % cls)
    for spec, picks in sorted(classes[cls]):
        w("{key=%s,\n" % lua(spec))
        for key in sorted(picks, key=lambda k: (int(k[:-1]), k[-1])):
            w("[%s]=%s,\n" % (lua(key), lua(picks[key])))
        w("},\n")
    w("},\n")
w("}\n")
io.open("../ForeverDungeonPrep/GearData.lua", "w", encoding="utf-8").write(out.getvalue())
print(len(items), "items,", sum(len(v) for v in classes.values()), "specs,", len(out.getvalue()), "bytes")
