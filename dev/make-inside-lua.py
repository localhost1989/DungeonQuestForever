#!/usr/bin/env python3
"""Write the block P.InsideSpots into ForeverDungeonPrep/BossRoute.lua from inside-spots.json.

Where the goals of a dungeon quest are inside the dungeon, on the floor plans of Dungeon
Quest Atlas: for each goal its spots (atlas key, floor, x, y, nearest boss index, room ru/en).
Run: python3 -I make-inside-lua.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "inside-spots.json")
DST = os.path.join(HERE, "..", "ForeverDungeonPrep", "BossRoute.lua")
BEGIN = "-- BEGIN INSIDE SPOTS"
END = "-- END INSIDE SPOTS"
MAX_SPOTS = 12
ATLAS_BOSSES = "/Applications/World of Warcraft/_forever_/Interface/AddOns/DungeonQuestAtlas/Data/Bosses.lua"


def atlas_npcs():
    """{atlas key: {boss index: npcID}} from the atlas's boss list (read, not copied)."""
    import re
    out, key, index = {}, None, 0
    for line in open(ATLAS_BOSSES, encoding="utf-8"):
        m = re.match(r"^    ([A-Z_0-9]+) = \{\s*$", line)
        if m:
            key, index = m.group(1), 0
            out[key] = {}
            continue
        if key and re.match(r"^        \{ ", line):
            index += 1
            n = re.search(r"npcID = (\d+)", line)
            if n:
                out[key][index] = int(n.group(1))
        elif key and re.match(r"^    \},?\s*$", line):
            key = None
    return out


NPCS = atlas_npcs()


def s(text):
    return "nil" if text in (None, "") else json.dumps(text, ensure_ascii=False)


def num(v):
    return ("%.3f" % v).rstrip("0").rstrip(".") if isinstance(v, float) else str(v)


def spot(key, floor, x, y, boss, room):
    boss = NPCS.get(key, {}).get(boss) if boss else None
    room = room or {}
    ru = room.get("ru") if isinstance(room, dict) else None
    en = room.get("en") if isinstance(room, dict) else None
    return "{%s,%d,%s,%s,%s,%s,%s}" % (s(key), floor, num(x), num(y), boss if boss else "nil", s(ru), s(en))


def main():
    data = json.load(open(SRC, encoding="utf-8"))
    by_quest = {}
    for e in data["entries"]:
        if e.get("status") not in ("point", "spread"):
            continue
        spots = []
        if e["status"] == "point":
            boss = (e.get("nearestBoss") or {}).get("index")
            spots.append(spot(e["atlasKey"], e["floor"], e["x"], e["y"], boss, e.get("room")))
        else:
            for c in sorted(e.get("clusters") or [], key=lambda c: -c.get("spawns", 0))[:MAX_SPOTS]:
                boss = (c.get("nearestBoss") or {}).get("index")
                room = {"ru": c.get("roomRu"), "en": c.get("room")}
                spots.append(spot(c["atlasKey"], c["floor"], c["x"], c["y"], boss, room))
        if not spots:
            continue
        item = e.get("item") or {}
        src = e.get("source") or (e.get("sources") or [{}])[0]
        what = item if item else src
        line = "{k=%s,kind=%s,item=%s,w={%s,%s},from={%s,%s},spread=%s,p={%s}}" % (
            s(e["dungeon"]), s(e["kind"]), item.get("id") or "nil",
            s(what.get("nameRu") or what.get("name")), s(what.get("name")),
            s(src.get("nameRu") or src.get("name")), s(src.get("name")),
            "true" if e["status"] == "spread" else "false", ",".join(spots))
        by_quest.setdefault(e["questID"], []).append(line)
    out = [BEGIN + ": generated by dungeon-quest-handoff/make-inside-lua.py from inside-spots.json; do not edit by hand",
           "-- [quest] = its goals inside: k dungeon, w what (ru, en), from who has it, spread or one place,",
           "-- p = {atlas key, floor, x, y, nearest boss (npc), room ru, room en}.",
           "P.InsideSpots = {"]
    for q in sorted(by_quest):
        out.append("    [%d]={%s}," % (q, ",".join(by_quest[q])))
    out.append("}")
    out.append(END)
    block = "\n".join(out)
    text = open(DST, encoding="utf-8").read()
    if BEGIN in text:
        a = text.index(BEGIN)
        b = text.index(END, a) + len(END)
        text = text[:a] + block + text[b:]
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    open(DST, "w", encoding="utf-8").write(text)
    print("quests", len(by_quest), "goals", sum(len(v) for v in by_quest.values()))


main()
