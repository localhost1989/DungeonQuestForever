#!/usr/bin/env python3
"""Write the block P.Rewards / P.RewardItems into ForeverDungeonPrep/Book.lua from quest-rewards.json.

What a quest gives, as the databases know it (VMaNGOS 1.12, Wowhead Forever where read): the
things to choose from, the things given, the money. The game's own answer, read while a quest
is in the log or open at its giver, is kept by the addon and stands over this.
Run: python3 -I make-rewards-lua.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "quest-rewards.json")
DST = os.path.join(HERE, "..", "ForeverDungeonPrep", "Book.lua")
BEGIN = "-- BEGIN REWARDS"
END = "-- END REWARDS"


def s(text):
    return "nil" if text in (None, "") else json.dumps(text, ensure_ascii=False)


def bytes_of(text):
    """A Russian name as Lua byte escapes: the locale tool reads Cyrillic in the code as words to translate."""
    if text in (None, ""):
        return "nil"
    out = []
    for ch in text:
        if ord(ch) < 128 and ch not in '"\\':
            out.append(ch)
        else:
            out.extend("\\%d" % b for b in ch.encode("utf-8"))
    return '"' + "".join(out) + '"'


def pairs(things):
    return ",".join("%d,%d" % (t["id"], t.get("count") or 1) for t in things)


def main():
    data = json.load(open(SRC, encoding="utf-8"))
    quests, used = [], set()
    for qid in sorted(data["quests"], key=int):
        q = data["quests"][qid]
        choice, given, money = q.get("choice") or [], q.get("items") or [], q.get("money") or 0
        if not (choice or given or money > 0):
            continue
        parts = []
        if choice:
            parts.append("c={%s}" % pairs(choice))
        if given:
            parts.append("g={%s}" % pairs(given))
        if money > 0:
            parts.append("m=%d" % money)
        quests.append("    [%d]={%s}," % (int(qid), ",".join(parts)))
        used.update(t["id"] for t in choice + given)
    items = []
    for iid in sorted(used):
        it = data["items"].get(str(iid)) or {}
        icon = it.get("icon")
        items.append("    [%d]={%s,%s,%s,%s}," % (iid, bytes_of(it.get("ru")), s(it.get("en")),
                                                it.get("quality") if it.get("quality") is not None else "nil",
                                                s(icon.lower() if icon else None)))
    out = [BEGIN + ": generated by dungeon-quest-handoff/make-rewards-lua.py from quest-rewards.json; do not edit by hand",
           "-- [quest] = {c things to choose from {item, count, ...}, g things given, m money in copper}",
           "P.Rewards = {"] + quests + ["}",
           "-- [item] = {name ru, name en, quality, icon}: said until the game tells its own",
           "P.RewardItems = {"] + items + ["}", END]
    block = "\n".join(out)
    text = open(DST, encoding="utf-8").read()
    if BEGIN in text:
        a = text.index(BEGIN)
        b = text.index(END, a) + len(END)
        text = text[:a] + block + text[b:]
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    open(DST, "w", encoding="utf-8").write(text)
    print("quests", len(quests), "items", len(items))


main()
