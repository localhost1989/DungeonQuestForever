# Советы по боссам (boss-tips.json: npc -> {run, name, ru, en, source, also}) -> таблица P.BossTips
# между -- BEGIN BOSS TIPS / -- END BOSS TIPS в ../ForeverDungeonPrep/BossRoute.lua; английский — в locale/en.json.
import io, json
tips = json.load(io.open("boss-tips.json", encoding="utf-8"))
en = json.load(io.open("locale/en.json", encoding="utf-8"))
lines = ["-- BEGIN BOSS TIPS: generated by dungeon-quest-handoff/make-boss-tips.py from boss-tips.json; do not edit by hand",
         "-- [boss] = what to do so the group lives: one or two short actions.",
         "P.BossTips = {"]
for npc in sorted(tips, key=int):
    t = tips[npc]
    if not t.get("ru"): continue
    ru = t["ru"].replace("\\", "").replace('"', "«")
    lines.append('    [%s]=L"%s",' % (npc, ru))
    for other in t.get("also") or []:
        lines.append('    [%s]=L"%s",' % (other, ru))
    en[ru] = t["en"].replace('"', "'")
lines.append("}")
lines.append("-- END BOSS TIPS")
block = "\n".join(lines) + "\n"
path = "../ForeverDungeonPrep/BossRoute.lua"
src = io.open(path, encoding="utf-8").read()
a, b = src.find("-- BEGIN BOSS TIPS"), src.find("-- END BOSS TIPS")
if a >= 0: src = src[:a] + block + src[b + len("-- END BOSS TIPS\n"):]
else: src = src.rstrip("\n") + "\n\n" + block
io.open(path, "w", encoding="utf-8").write(src)
json.dump(en, io.open("locale/en.json", "w", encoding="utf-8"), ensure_ascii=False, indent=0)
print(sum(1 for t in tips.values() if t.get("ru")), "tips")
